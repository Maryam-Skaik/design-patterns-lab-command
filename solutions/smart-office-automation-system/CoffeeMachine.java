package commandpattern;

/*
 * Receiver Class
 * --------------
 * Represents the office coffee machine.
 */
public class CoffeeMachine {

    /*
     * Starts coffee preparation.
     */
    public void start() {
        System.out.println("Coffee Machine Started");
    }

    /*
     * Stops coffee preparation.
     */
    public void stop() {
        System.out.println("Coffee Machine Stopped");
    }
}
