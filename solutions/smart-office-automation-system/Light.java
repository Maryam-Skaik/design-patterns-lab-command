package commandpattern;

/*
 * Receiver Class
 * --------------
 * Represents the office lighting system.
 */
public class Light {

    /*
     * Turns the light ON.
     */
    public void turnOn() {
        System.out.println("Office Light is ON");
    }

    /*
     * Turns the light OFF.
     */
    public void turnOff() {
        System.out.println("Office Light is OFF");
    }
}
