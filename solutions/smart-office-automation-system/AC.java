package commandpattern;

/*
 * Receiver Class
 * --------------
 * Represents the office air conditioner.
 */
public class AC {

    /*
     * Turns the AC ON.
     */
    public void start() {
        System.out.println("AC Started");
    }

    /*
     * Turns the AC OFF.
     */
    public void stop() {
        System.out.println("AC Stopped");
    }
}
