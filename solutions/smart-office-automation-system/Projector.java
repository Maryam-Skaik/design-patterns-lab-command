package commandpattern;

/*
 * Receiver Class
 * --------------
 * Represents the office projector.
 */
public class Projector {

    /*
     * Starts the projector.
     */
    public void start() {
        System.out.println("Projector Started");
    }

    /*
     * Stops the projector.
     */
    public void stop() {
        System.out.println("Projector Stopped");
    }
}
